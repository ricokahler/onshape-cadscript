export type CoverageStatus =
  "stable" | "experimental" | "raw escape hatch" | "planned" | "not planned";
export type CoverageArea = "sketch" | "feature" | "query" | "rest" | "mcp" | "live";

export interface CoverageEntry {
  readonly id: string;
  readonly area: CoverageArea;
  readonly capability: string;
  readonly onshapeSurface: string;
  readonly cadscriptApi: string;
  readonly status: CoverageStatus;
  readonly tests: string;
  readonly documentation: string;
  readonly release: string;
  readonly milestone: "v0.1" | "v0.2" | "v0.3" | "v1.0" | "none";
}

const entry = (
  area: CoverageArea,
  id: string,
  capability: string,
  onshapeSurface: string,
  cadscriptApi: string,
  status: CoverageStatus,
  milestone: CoverageEntry["milestone"],
  tests = "unit",
  documentation = "guide",
  release = "0.1.0",
): CoverageEntry => ({
  area,
  id: `${area}.${id}`,
  capability,
  onshapeSurface,
  cadscriptApi,
  status,
  tests,
  documentation,
  release,
  milestone,
});

